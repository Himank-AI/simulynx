import type { Band, CareerStage, CollaborationStyle, Persona, SkillProficiency, WorkModel } from '../types.ts'

type Level = SkillProficiency['level']

interface PersonaInput {
  personaId: string
  roleId: string
  departmentId: string
  careerStage: CareerStage
  location: string
  workModel: WorkModel
  skills: [string, Level][]
  emerging?: string[]
  gaps: string[]
  goals: string[]
  trajectory: string
  mobility: Band
  learning: Band
  workload: number
  experience: number
  pattern: string
  tenure: number
  change: Band
  adapt: Band
  ready: Band
  collaboration: CollaborationStyle
  manager?: string
  collaborators?: string[]
  transitions: string[]
  receiving?: string[]
  access?: string
}

function persona(input: PersonaInput): Persona {
  return {
    personaId: input.personaId,
    roleId: input.roleId,
    departmentId: input.departmentId,
    careerStage: input.careerStage,
    location: input.location,
    workModel: input.workModel,
    currentSkills: input.skills.map(([skillId, level]) => ({ skillId, level })),
    emergingSkillIds: input.emerging ?? [],
    skillGapIds: input.gaps,
    careerGoals: input.goals,
    careerTrajectory: input.trajectory,
    mobilityPotential: input.mobility,
    learningCapacity: input.learning,
    workload: input.workload,
    experienceYears: input.experience,
    workPattern: input.pattern,
    accessibilityContext: input.access,
    organizationalTenureYears: input.tenure,
    changeTolerance: input.change,
    learningAdaptability: input.adapt,
    mobilityReadiness: input.ready,
    collaborationPreference: input.collaboration,
    managerPersonaId: input.manager,
    collaborationPersonaIds: input.collaborators ?? [],
    potentialTransitionRoleIds: input.transitions,
    receivingDepartmentIds: input.receiving ?? [],
  }
}

